#include "textflag.h"

DATA avxCtrl<>+0(SB)/8, $0x1F1F1F1F1F1F1F1F
DATA avxCtrl<>+8(SB)/8, $0x1F1F1F1F1F1F1F1F
DATA avxCtrl<>+16(SB)/8, $0x1F1F1F1F1F1F1F1F
DATA avxCtrl<>+24(SB)/8, $0x1F1F1F1F1F1F1F1F
GLOBL avxCtrl<>(SB), (NOPTR+RODATA), $32

DATA avxQuote<>+0(SB)/8, $0x2222222222222222
DATA avxQuote<>+8(SB)/8, $0x2222222222222222
DATA avxQuote<>+16(SB)/8, $0x2222222222222222
DATA avxQuote<>+24(SB)/8, $0x2222222222222222
GLOBL avxQuote<>(SB), (NOPTR+RODATA), $32

DATA avxBslash<>+0(SB)/8, $0x5C5C5C5C5C5C5C5C
DATA avxBslash<>+8(SB)/8, $0x5C5C5C5C5C5C5C5C
DATA avxBslash<>+16(SB)/8, $0x5C5C5C5C5C5C5C5C
DATA avxBslash<>+24(SB)/8, $0x5C5C5C5C5C5C5C5C
GLOBL avxBslash<>(SB), (NOPTR+RODATA), $32

TEXT ·findSafeStringAVX2(SB), NOSPLIT, $0-24
	MOVQ p+0(FP), SI
	MOVQ n+8(FP), CX
	XORQ AX, AX
	VMOVDQU avxCtrl<>(SB), Y1
	VMOVDQU avxQuote<>(SB), Y2
	VMOVDQU avxBslash<>(SB), Y3
	VPXOR   Y4, Y4, Y4

fs_loop:
	CMPQ AX, CX
	JAE  fs_done
	VMOVDQU   (SI)(AX*1), Y0
	VPSUBUSB  Y1, Y0, Y5
	VPCMPEQB  Y4, Y5, Y5
	VPCMPEQB  Y2, Y0, Y6
	VPCMPEQB  Y3, Y0, Y7
	VPOR      Y6, Y5, Y5
	VPOR      Y7, Y5, Y5
	VPMOVMSKB Y5, DX
	TESTL     DX, DX
	JNZ       fs_found
	ADDQ      $32, AX
	JMP       fs_loop

fs_found:
	BSFL DX, DX
	ADDQ DX, AX

fs_done:
	VZEROUPPER
	MOVQ AX, ret+16(FP)
	RET

TEXT ·quoteCopyAVX2(SB), NOSPLIT, $0-32
	MOVQ src+0(FP), SI
	MOVQ n+8(FP), CX
	MOVQ dst+16(FP), DI
	XORQ AX, AX
	VMOVDQU avxCtrl<>(SB), Y1
	VMOVDQU avxQuote<>(SB), Y2
	VMOVDQU avxBslash<>(SB), Y3
	VPXOR   Y4, Y4, Y4

qc_loop:
	CMPQ AX, CX
	JAE  qc_done
	VMOVDQU   (SI)(AX*1), Y0
	VPSUBUSB  Y1, Y0, Y5
	VPCMPEQB  Y4, Y5, Y5
	VPCMPEQB  Y2, Y0, Y6
	VPCMPEQB  Y3, Y0, Y7
	VPOR      Y6, Y5, Y5
	VPOR      Y7, Y5, Y5
	VPMOVMSKB Y5, DX
	TESTL     DX, DX
	JNZ       qc_done
	VMOVDQU   Y0, (DI)(AX*1)
	ADDQ      $32, AX
	JMP       qc_loop

qc_done:
	VZEROUPPER
	MOVQ AX, ret+24(FP)
	RET

TEXT ·specialMask64AVX2(SB), NOSPLIT, $0-16
	MOVQ      p+0(FP), SI
	VMOVDQU   avxCtrl<>(SB), Y1
	VMOVDQU   avxQuote<>(SB), Y2
	VMOVDQU   avxBslash<>(SB), Y3
	VPXOR     Y4, Y4, Y4
	VMOVDQU   (SI), Y0
	VPSUBUSB  Y1, Y0, Y5
	VPCMPEQB  Y4, Y5, Y5
	VPCMPEQB  Y2, Y0, Y6
	VPCMPEQB  Y3, Y0, Y7
	VPOR      Y6, Y5, Y5
	VPOR      Y7, Y5, Y5
	VPMOVMSKB Y5, AX
	VMOVDQU   32(SI), Y0
	VPSUBUSB  Y1, Y0, Y5
	VPCMPEQB  Y4, Y5, Y5
	VPCMPEQB  Y2, Y0, Y6
	VPCMPEQB  Y3, Y0, Y7
	VPOR      Y6, Y5, Y5
	VPOR      Y7, Y5, Y5
	VPMOVMSKB Y5, DX
	SHLQ      $32, DX
	ORQ       DX, AX
	VZEROUPPER
	MOVQ      AX, ret+8(FP)
	RET
