TEXT ·findSafeStringAVX2(SB), NOSPLIT, $0-24
	MOVQ p+0(FP), SI
	MOVQ n+8(FP), CX
	XORQ AX, AX
	VMOVDQU avxCtrl<>(SB), Y1
	VMOVDQU avxQuote<>(SB), Y2
	VMOVDQU avxBslash<>(SB), Y3
	VPXOR   Y4, Y4, Y4

fs_loop:
	CMPQ AX, CX
	JAE  fs_done
	VMOVDQU   (SI)(AX*1), Y0
	VPSUBUSB  Y1, Y0, Y5
	VPCMPEQB  Y4, Y5, Y5
	VPCMPEQB  Y2, Y0, Y6
	VPCMPEQB  Y3, Y0, Y7
	VPOR      Y6, Y5, Y5
	VPOR      Y7, Y5, Y5
	VPMOVMSKB Y5, DX
	TESTL     DX, DX
	JNZ       fs_found
	ADDQ      $32, AX
	JMP       fs_loop

fs_found:
	BSFL DX, DX
	ADDQ DX, AX

fs_done:
	VZEROUPPER
	MOVQ AX, ret+16(FP)
	RET

