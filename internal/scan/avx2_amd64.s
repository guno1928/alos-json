	CMPQ AX, CX
	JAE  qc_done
	VMOVDQU   (SI)(AX*1), Y0
	VPSUBUSB  Y1, Y0, Y5
	VPCMPEQB  Y4, Y5, Y5
	VPCMPEQB  Y2, Y0, Y6
	VPCMPEQB  Y3, Y0, Y7
	VPOR      Y6, Y5, Y5
	VPOR      Y7, Y5, Y5
