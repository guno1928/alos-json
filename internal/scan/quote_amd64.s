//go:build amd64 && !purego

#include "textflag.h"

#define DOUBLE_STEP 64
#define DOUBLE_ROOM 70
#define WIDE_STEP 32
#define WIDE_ROOM 38
#define HALF_STEP 16
#define HALF_ROOM 22
#define ESCAPE_ROOM 6
#define DENSE_ROOM 224
#define PAGE_MASK 4095
#define LAST_HALF_LOAD 4080
#define ESCAPE_LEN_SHIFT 56
#define LONG_ESCAPE_BIT 58
#define SHORT_ESCAPE_LEN 2
#define LONG_ESCAPE_TAIL 4
#define CTRL_SPLAT 0x1F1F1F1F
#define QUOTE_SPLAT 0x22222222
#define BSLASH_SPLAT 0x5C5C5C5C

#define SPECIAL_MASK(V, CTRL, QUOTE, BSLASH, OUT, TA, TB) \
	VPMINUB  CTRL, V, OUT; \
	VPCMPEQB V, OUT, OUT; \
	VPCMPEQB QUOTE, V, TA; \
	VPCMPEQB BSLASH, V, TB; \
	VPOR     TA, OUT, OUT; \
	VPOR     TB, OUT, OUT

TEXT ·quoteEscapeAVX2(SB), NOSPLIT, $0-48
	MOVQ dst+0(FP), DI
	MOVQ room+8(FP), R8
	MOVQ src+16(FP), SI
	MOVQ n+24(FP), R13
	XORQ AX, AX
	XORQ BX, BX
	LEAQ ·quoteEscapes(SB), R10
	LEAQ -WIDE_STEP(R13), R14
	MOVL $CTRL_SPLAT, R11
	MOVQ R11, X1
	VPBROADCASTD X1, Y1
	MOVL $QUOTE_SPLAT, R11
	MOVQ R11, X2
	VPBROADCASTD X2, Y2
	MOVL $BSLASH_SPLAT, R11
	MOVQ R11, X3
	VPBROADCASTD X3, Y3

wide:
	CMPQ AX, R14
	JGT  narrow
	LEAQ WIDE_ROOM(BX), R9
	CMPQ R9, R8
	JA   done
	VMOVDQU (SI)(AX*1), Y0
	VMOVDQU Y0, (DI)(BX*1)
	SPECIAL_MASK(Y0, Y1, Y2, Y3, Y5, Y6, Y7)
	VPMOVMSKB Y5, DX
	TESTL DX, DX
	JNZ   found
	ADDQ $WIDE_STEP, AX
	ADDQ $WIDE_STEP, BX

double:
	MOVQ R13, R12
	SUBQ AX, R12
	CMPQ R12, $DOUBLE_STEP
	JB   wide
	LEAQ DOUBLE_ROOM(BX), R9
	CMPQ R9, R8
	JA   wide
	VMOVDQU (SI)(AX*1), Y0
	VMOVDQU WIDE_STEP(SI)(AX*1), Y8
	VMOVDQU Y0, (DI)(BX*1)
	VMOVDQU Y8, WIDE_STEP(DI)(BX*1)
	SPECIAL_MASK(Y0, Y1, Y2, Y3, Y5, Y6, Y7)
	SPECIAL_MASK(Y8, Y1, Y2, Y3, Y9, Y10, Y11)
	VPOR    Y5, Y9, Y10
	VPTEST  Y10, Y10
	JNZ     doublefound
	ADDQ $DOUBLE_STEP, AX
	ADDQ $DOUBLE_STEP, BX
	JMP  double

doublefound:
	VPMOVMSKB Y5, DX
	TESTL DX, DX
	JNZ   found
	VPMOVMSKB Y9, DX
	ADDQ $WIDE_STEP, AX
	ADDQ $WIDE_STEP, BX

found:
	MOVQ R13, R12
	SUBQ AX, R12
	CMPQ R12, $DOUBLE_STEP
	JB   single
	LEAQ DENSE_ROOM(BX), R9
	CMPQ R9, R8
	JA   single
	MOVQ AX, R12

dense:
	BSFL DX, CX
	ADDQ R12, CX
	VMOVDQU (SI)(AX*1), Y0
	VMOVDQU Y0, (DI)(BX*1)
	ADDQ CX, BX
	SUBQ AX, BX
	MOVBLZX (SI)(CX*1), R9
	MOVQ (R10)(R9*8), R9
	LEAQ 1(CX), AX
	MOVQ R9, (DI)(BX*1)
	SHRQ $ESCAPE_LEN_SHIFT, R9
	ADDQ R9, BX
	LEAL -1(DX), R11
	ANDL R11, DX
	JNZ  dense
	JMP  wide

single:
	BSFL DX, DX
	ADDQ DX, AX
	ADDQ DX, BX

escape:
	MOVBLZX (SI)(AX*1), DX
	MOVQ (R10)(DX*8), R9
	INCQ AX
	BTQ  $LONG_ESCAPE_BIT, R9
	JCS  escapelong
	MOVW R9, (DI)(BX*1)
	ADDQ $SHORT_ESCAPE_LEN, BX
	JMP  wide

escapelong:
	MOVL R9, (DI)(BX*1)
	SHRQ $32, R9
	MOVW R9, LONG_ESCAPE_TAIL(DI)(BX*1)
	ADDQ $ESCAPE_ROOM, BX
	JMP  wide

narrow:
	MOVQ R13, R12
	SUBQ AX, R12
	JZ   done
	MOVQ R8, R9
	SUBQ BX, R9
	CMPQ R12, $HALF_STEP
	JB   tail
	CMPQ R9, $HALF_ROOM
	JB   done
	VMOVDQU (SI)(AX*1), X0
	VMOVDQU X0, (DI)(BX*1)
	SPECIAL_MASK(X0, X1, X2, X3, X5, X6, X7)
	VPMOVMSKB X5, DX
	TESTL DX, DX
	JNZ   single
	ADDQ $HALF_STEP, AX
	ADDQ $HALF_STEP, BX
	JMP  narrow

tail:
	LEAQ ESCAPE_ROOM(R12), R11
	CMPQ R9, R11
	JB   done
	LEAQ (SI)(AX*1), R11
	MOVL R11, DX
	ANDL $PAGE_MASK, DX
	CMPL DX, $LAST_HALF_LOAD
	JA   tailback
	VMOVDQU (R11), X0
	SPECIAL_MASK(X0, X1, X2, X3, X5, X6, X7)
	VPMOVMSKB X5, DX
	JMP  tailmask

tailback:
	VMOVDQU -HALF_STEP(SI)(R13*1), X0
	SPECIAL_MASK(X0, X1, X2, X3, X5, X6, X7)
	VPMOVMSKB X5, DX
	MOVQ $HALF_STEP, CX
	SUBQ R12, CX
	SHRL CX, DX

tailmask:
	BTSL R12, DX
	BSFL DX, DX
	LEAQ (DI)(BX*1), R9
	CMPQ DX, $8
	JAE  copy8
	CMPQ DX, $4
	JAE  copy4
	CMPQ DX, $2
	JAE  copy2
	TESTQ DX, DX
	JZ   copied
	MOVBLZX (R11), CX
	MOVB CX, (R9)
	JMP  copied

copy2:
	MOVWLZX (R11), CX
	MOVW CX, (R9)
	MOVWLZX -2(R11)(DX*1), CX
	MOVW CX, -2(R9)(DX*1)
	JMP  copied

copy4:
	MOVL (R11), CX
	MOVL CX, (R9)
	MOVL -4(R11)(DX*1), CX
	MOVL CX, -4(R9)(DX*1)
	JMP  copied

copy8:
	MOVQ (R11), CX
	MOVQ CX, (R9)
	MOVQ -8(R11)(DX*1), CX
	MOVQ CX, -8(R9)(DX*1)

copied:
	ADDQ DX, AX
	ADDQ DX, BX
	CMPQ DX, R12
	JNE  escape

done:
	VZEROUPPER
	MOVQ BX, written+32(FP)
	MOVQ AX, consumed+40(FP)
	RET
